#!/usr/bin/env python3
"""Generates the armoury: content/weapons/<maker>_<model>.cfg.

The ten hand-written weapons (service_rifle, sidearm, the three doctrine
weapons, and the first shop five) are left alone. Everything this writes is
built from seven archetypes - one per silhouette the viewmodel can draw -
scaled by a tier and bent by a maker, and then handed out over the ways a
weapon can come to you (see WeaponDef::source in src/Content.h).

Re-running it rewrites only the files it owns (every one it writes starts
with the GENERATED line), so tuning a number here and running it again is
how the whole armoury is re-balanced. It also prints the reward assignments
it expects the missions, ranks and bounties to carry; tools/make_weapons.py
--apply writes those lines into the content files as well.

    python3 tools/make_weapons.py [--apply]
"""
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "content")
WEAPONS = os.path.join(ROOT, "weapons")
MARK = "# GENERATED by tools/make_weapons.py - edit the generator, not this file."

# The seven silhouettes, and what a tier-1 weapon of each does.
ARCH = {
    "rifle":     dict(damage=22, fi=0.110, mag=30, res=180, reload=1.6, spread=0.006, rng=200, hs=2.0, pellets=1),
    "carbine":   dict(damage=18, fi=0.090, mag=32, res=192, reload=1.4, spread=0.008, rng=160, hs=2.0, pellets=1),
    "smg":       dict(damage=11, fi=0.060, mag=40, res=240, reload=1.3, spread=0.014, rng=90,  hs=1.8, pellets=1),
    "marksman":  dict(damage=46, fi=0.380, mag=10, res=60,  reload=2.0, spread=0.0015, rng=300, hs=2.6, pellets=1),
    "shotgun":   dict(damage=13, fi=0.760, mag=6,  res=48,  reload=2.6, spread=0.055, rng=34,  hs=1.5, pellets=8),
    "pistol":    dict(damage=20, fi=0.180, mag=12, res=96,  reload=1.2, spread=0.004, rng=120, hs=2.0, pellets=1),
    "induction": dict(damage=26, fi=0.220, mag=16, res=96,  reload=1.9, spread=0.003, rng=180, hs=1.8, pellets=1, pierce=True),
}
TIER_DMG = {1: 1.00, 2: 1.10, 3: 1.22, 4: 1.36, 5: 1.52}
TIER_COST = {1: 120, 2: 220, 3: 380, 4: 600, 5: 900}
ARCH_COST = {"rifle": 1.0, "carbine": 0.95, "smg": 0.9, "marksman": 1.15, "shotgun": 1.05,
             "pistol": 0.7, "induction": 1.2}
# What a tier is released at, for the weapons that are bought.
TIER_RANK = {1: "", 2: "probationer", 3: "hull_walker", 4: "spine_runner", 5: "strider_2"}

# Makers: a prefix, a flavour, and how they bend the archetype.
MAKERS = {
    "ka":   dict(name="KOUROU ARMS", prefix="KA", mods=dict(reload=0.9),
                 line="Ground issue from the programme's own works. Nothing clever, nothing that jams."),
    "cw":   dict(name="CRADLE WORKS", prefix="CW", mods=dict(damage=1.04, mag=1.1),
                 line="Rebuilt on the Cradle out of what came back. Voss signs every one."),
    "hal":  dict(name="HALCYON", prefix="HX", mods=dict(spread=0.6, fi=1.12, damage=1.08, hs=1.1),
                 line="Precision work. Slower to speak, and it means what it says."),
    "br":   dict(name="BRANDT", prefix="BR", mods=dict(damage=1.22, fi=1.18, mag=0.85, reload=1.08),
                 line="Heavy. Every round lands like a decision."),
    "ves":  dict(name="VESPER", prefix="VS", mods=dict(fi=0.82, damage=0.9, mag=1.15, reload=0.92),
                 line="Light and fast. Empties itself before the other one has finished thinking."),
    "salv": dict(name="ARK SALVAGE", prefix="AS", mods=dict(damage=0.95, reload=1.15, pierce=True),
                 line="Stripped off the ark. Whatever it was built to shoot, it goes through it."),
    "ch":   dict(name="CHOIR", prefix="CH", mods=dict(damage=1.12, spread=0.7, pierce=True, hs=1.15),
                 line="It hums when it is loaded. Nobody on the Cradle will say what it was."),
}

MODELS = {
    "rifle":     ["SENTRY", "HALYARD", "TALON", "BASTION", "MERIDIAN", "LONGBOW"],
    "carbine":   ["SPRITE", "PIPIT", "MERLIN", "SWIFT", "LARK", "TERN"],
    "smg":       ["HORNET", "WASP", "GNAT", "MAYFLY", "SWARM", "CICADA"],
    "marksman":  ["NEEDLE", "OSPREY", "SPIRE", "SIGHTLINE", "PARALLAX", "ZENITH"],
    "shotgun":   ["BREAKER", "RAM", "DOORMAN", "HAMMERHEAD", "BULLHORN", "CLAMOUR"],
    "pistol":    ["WREN", "SPARROW", "FINCH", "JACKDAW", "MAGPIE", "NIGHTJAR"],
    "induction": ["ARC", "COIL", "LATTICE", "FILAMENT", "CANTOR", "HYMN"],
}

ROMAN = {1: "I", 2: "II", 3: "III", 4: "IV", 5: "V"}
ORDER = ["rifle", "carbine", "smg", "marksman", "shotgun", "pistol", "induction"]


def plan():
    """Every weapon this writes: (maker, archetype, tier, source, sold_by)."""
    out = []
    # SHOP: Ondo sells Kourou Arms on Earth, Voss sells Cradle Works in orbit.
    for t in (1, 2):
        for a in ORDER:
            out.append(("ka", a, t, "shop", "ondo"))
    for a in ("rifle", "pistol"):
        out.append(("ka", a, 3, "shop", "ondo"))
    for t in (3, 4):
        for a in ORDER:
            out.append(("cw", a, t, "shop", "voss"))
    # DROPS: the field. Vesper is common, Brandt heavier, salvage deepest.
    for a in ORDER:
        out.append(("ves", a, 1 if a in ("smg", "pistol", "carbine") else 2, "drop", ""))
    for a in ORDER:
        out.append(("br", a, 3, "drop", ""))
    for a in ORDER:
        out.append(("salv", a, 4, "drop", ""))
    for a in ORDER:
        out.append(("ves", a, 5 if a in ("rifle", "marksman", "induction") else 4, "drop", ""))
    # MISSION first-clear rewards.
    for a, t in [("rifle", 2), ("marksman", 2), ("shotgun", 3), ("pistol", 2), ("carbine", 3),
                 ("smg", 3), ("induction", 3), ("rifle", 4), ("marksman", 4), ("shotgun", 4),
                 ("carbine", 4), ("induction", 5)]:
        out.append(("hal" if t < 5 else "ch", a, t, "mission", ""))
    # RANK: one on each rung from probationer up.
    for a, t in [("pistol", 1), ("carbine", 2), ("rifle", 3), ("smg", 3), ("marksman", 4),
                 ("shotgun", 4), ("induction", 5), ("rifle", 5)]:
        out.append(("ves" if t < 5 else "ch", a, t, "rank", ""))
    # BOUNTY rewards.
    for a, t in [("smg", 2), ("pistol", 3), ("shotgun", 2), ("rifle", 3), ("induction", 4), ("marksman", 5)]:
        out.append(("br" if t < 5 else "ch", a, t, "bounty", ""))
    # THE ROOK.
    for a, t in [("pistol", 4), ("smg", 4), ("carbine", 5), ("shotgun", 5), ("rifle", 5), ("marksman", 3)]:
        out.append(("ch" if t == 5 else "hal", a, t, "rook", ""))
    return out


def build(maker, arch, tier, source, sold_by, used):
    base = dict(ARCH[arch])
    m = MAKERS[maker]
    mods = m["mods"]
    # Pick the first model name not already taken by this maker+archetype.
    for model in MODELS[arch]:
        key = (maker, model)
        if key not in used:
            used.add(key)
            break
    dmg = base["damage"] * TIER_DMG[tier] * mods.get("damage", 1.0)
    fi = base["fi"] * mods.get("fi", 1.0)
    mag = max(4, int(round(base["mag"] * mods.get("mag", 1.0) * (1.0 + 0.04 * (tier - 1)))))
    res = int(round(base["res"] * (1.0 + 0.05 * (tier - 1)) / 4.0) * 4)
    reload = base["reload"] * mods.get("reload", 1.0) * (1.0 - 0.03 * (tier - 1))
    spread = base["spread"] * mods.get("spread", 1.0) * (1.0 - 0.06 * (tier - 1))
    hs = base["hs"] * mods.get("hs", 1.0)
    pierce = base.get("pierce", False) or mods.get("pierce", False)
    cost = int(round(TIER_COST[tier] * ARCH_COST[arch] / 10.0) * 10)
    rank = ""
    if source == "shop":
        rank = TIER_RANK[tier]
    elif source == "rook":
        rank = TIER_RANK[tier]
        cost = int(round(cost * 1.4 / 10.0) * 10)
    else:
        cost = 0 if source != "rook" else cost
    # Ids: maker_model, lowercased, spaces to underscores.
    wid = f"{maker}_{model.lower().replace(' ', '_')}"
    name = f"{m['prefix']}-{tier}{ORDER.index(arch) + 1} {model}"
    if tier > 1:
        name += f" MK {ROMAN[tier]}"
    lines = [
        MARK,
        f"name = {name}",
        f"maker = {m['name']}",
        f"tier = {tier}",
        f"source = {source}",
    ]
    if sold_by:
        lines.append(f"sold_by = {sold_by}")
    lines += [
        f"shape = {arch}",
        f"damage = {dmg:.1f}",
        f"headshot_multiplier = {hs:.2f}",
        f"fire_interval = {fi:.3f}",
        f"reload_time = {reload:.2f}",
        f"mag_size = {mag}",
        f"reserve = {res}",
        f"spread = {spread:.4f}",
        f"range = {base['rng']}",
    ]
    if base["pellets"] > 1:
        lines.append(f"pellets = {base['pellets']}")
    if pierce:
        lines.append("pierce = true")
    lines.append(f"cost = {cost}")
    if rank:
        lines.append(f"rank_required = {rank}")
    lines.append(f"blurb = {m['line']}")
    return wid, "\n".join(lines) + "\n"


def main():
    apply = "--apply" in sys.argv
    # Clear what this generator wrote last time, so a renamed model does not
    # leave its old file behind.
    for f in os.listdir(WEAPONS):
        p = os.path.join(WEAPONS, f)
        with open(p) as fh:
            if fh.readline().strip() == MARK:
                os.remove(p)
    used = set()
    by_source = {}
    for maker, arch, tier, source, sold_by in plan():
        wid, text = build(maker, arch, tier, source, sold_by, used)
        with open(os.path.join(WEAPONS, wid + ".cfg"), "w") as fh:
            fh.write(text)
        by_source.setdefault(source, []).append(wid)
    total = len(os.listdir(WEAPONS))
    print(f"wrote {sum(len(v) for v in by_source.values())} weapons; {total} in content/weapons")
    for k, v in by_source.items():
        print(f"  {k:8s} {len(v)}")

    # Who hands over the non-shop ones.
    missions = ["earth_hangar", "earth_causeway", "earth_launch", "breach", "hold", "promenade",
                "greenhouse", "archive", "foundry", "relay", "vault", "conductor"]
    ranks = ["probationer", "strider_3", "hull_walker", "spine_runner", "strider_2",
             "strider_1", "senior", "lead"]
    bounties = ["bright_head_count", "ondo_scrap_rate", "hale_fence_line", "kaur_down_the_spine",
                "odil_use_your_kit", "rook_been_somewhere"]
    pairs = [("missions", "reward_weapon", missions, by_source.get("mission", [])),
             ("ranks", "grant_weapon", ranks, by_source.get("rank", [])),
             ("bounties", "reward_item", bounties, by_source.get("bounty", []))]
    for folder, key, owners, weapons in pairs:
        for owner, wid in zip(owners, weapons):
            value = ("weapon:" + wid) if key == "reward_item" else wid
            print(f"  {folder}/{owner}.cfg: {key} = {value}")
            if not apply:
                continue
            p = os.path.join(ROOT, folder, owner + ".cfg")
            if not os.path.exists(p):
                print(f"    (skipped: {p} does not exist yet)")
                continue
            with open(p) as fh:
                s = fh.read()
            if re.search(rf"^{key} = .*$", s, re.M):
                s = re.sub(rf"^{key} = .*$", f"{key} = {value}", s, count=1, flags=re.M)
            else:
                s = s.rstrip("\n") + f"\n{key} = {value}\n"
            with open(p, "w") as fh:
                fh.write(s)


if __name__ == "__main__":
    main()
