static const size_t kFontCount = sizeof(kFont) / sizeof(kFont[0]);

// Case-insensitive; an unsupported character (or anything below ' ')
// renders as blank space rather than a missing-glyph box, so a stray
// character in content data degrades gracefully instead of looking broken.
inline const Glyph* findGlyph(char c) {
  if (c >= 'a' && c <= 'z') c = (char)(c - 'a' + 'A');
  for (size_t i = 0; i < kFontCount; i++) {
    if (kFont[i].ch == c) return &kFont[i];
  }
  return nullptr;
}
